const $ = (s) => document.querySelector(s);
const form = $('#prompt-form'), input = $('#prompt-input'), send = $('#send-button');
const messages = $('#chat-messages');
const sleep = (ms) => new Promise(resolve => setTimeout(resolve, ms));
let busy = false;

async function checkHealth() {
  try {
    const r = await fetch('/api/health');
    if (!r.ok) throw new Error('Unavailable');
    const data = await r.json();
    $('#engine-status').textContent = `${data.engine} configured · ${data.model}`;
  } catch {
    $('#engine-status').textContent = 'Backend not reachable';
  }
}
checkHealth();

function setStep(name, state, detail, label) {
  const el = $(`#step-${name}`);
  el.classList.remove('active', 'passed', 'failed', 'skipped');
  if (state) el.classList.add(state);
  el.querySelector('.step-state').textContent = label || ({active:'…',passed:'✓',failed:'!',skipped:'—'}[state] || '—');
  $(`#detail-${name}`).textContent = detail;
}
function resetPipeline() {
  ['input','model','output','delivery'].forEach(n => setStep(n, '', ({input:'Waiting for prompt',model:'Waiting for input check',output:'Waiting for model response',delivery:'Waiting for checks'})[n], '—'));
  $('#pipeline-state').textContent = 'PROCESSING';
  $('#pipeline-result').className = 'pipeline-result';
  $('#pipeline-result').innerHTML = '<span class="result-mark">◌</span><div><b>Processing request</b><small>Follow the checkpoints as they complete.</small></div>';
}
function addMessage(kind, text, label) {
  const wrap = document.createElement('div'); wrap.className = `message ${kind}`;
  const avatar = document.createElement('div'); avatar.className = 'message-avatar'; avatar.textContent = kind === 'user' ? 'YOU' : 'S';
  const content = document.createElement('div'); content.className = 'message-content';
  const title = document.createElement('b'); title.textContent = label || (kind === 'user' ? 'You' : 'Sentinel assistant');
  const body = document.createElement('p'); body.textContent = text;
  content.append(title, body); wrap.append(avatar, content); messages.append(wrap); messages.scrollTop = messages.scrollHeight;
}
function showResult(title, detail, status) {
  const el = $('#pipeline-result'); el.className = `pipeline-result ${status || ''}`;
  el.innerHTML = '';
  const mark = document.createElement('span'); mark.className = 'result-mark'; mark.textContent = status === 'success' ? '✓' : status === 'danger' ? '!' : 'i';
  const box = document.createElement('div'), b = document.createElement('b'), small = document.createElement('small');
  b.textContent = title; small.textContent = detail; box.append(b, small); el.append(mark, box);
}

async function runPipeline(prompt) {
  if (busy) return; busy = true; send.disabled = true; send.innerHTML = 'Running <span class="spinner"></span>';
  resetPipeline();
  addMessage('user', prompt, 'You');
  try {
    setStep('input','active','Inspecting request against configured rules…');
    const responsePromise = fetch('/api/chat', {method:'POST', headers:{'Content-Type':'application/json'}, body:JSON.stringify({prompt})});
    // Animate the first checkpoint while the backend performs the real check and model call.
    const response = await responsePromise;
    const data = await response.json();
    await sleep(620);
    const cat = data.input?.category || 'UNKNOWN';
    if (cat === 'RESTRICT') {
      setStep('input','failed',`RESTRICT · ${data.input.reason}`,'BLOCKED');
      setStep('model','skipped','Not called: input was restricted','SKIPPED');
      setStep('output','skipped','No model output to inspect','SKIPPED');
      setStep('delivery','passed','Safe fallback delivered','✓');
      $('#pipeline-state').textContent = 'STOPPED AT INPUT';
      showResult('Request stopped at input','The local model was not called. A fallback response was returned.','danger');
    } else {
      setStep('input','passed',`${cat} · ${data.input.reason}`,'PASSED');
      setStep('model','active','Request processed by local Ollama model…'); await sleep(650);
      if (!data.model_attempted) throw new Error('The model stage did not run.');
      if (data.final_status === 'model_unavailable') {
        setStep('model','failed',data.error || 'Ollama unavailable','ERROR');
        setStep('output','skipped','No generated answer to inspect','SKIPPED');
        setStep('delivery','passed','Safe fallback delivered','✓');
        $('#pipeline-state').textContent = 'MODEL UNAVAILABLE';
        showResult('Local model unavailable','Start Ollama and confirm the configured model is installed.','danger');
      } else {
        setStep('model','passed',`Generated by ${data.model}`,'PASSED'); await sleep(450);
        setStep('output','active','Inspecting generated response…'); await sleep(500);
        if (data.output?.allowed) {
          setStep('output','passed',data.output.reason,'PASSED');
          setStep('delivery','passed','Checked answer delivered to chat','✓');
          $('#pipeline-state').textContent = 'ALL CHECKS PASSED';
          showResult('Response approved','Both configured guardrail stages passed.','success');
        } else {
          setStep('output','failed',data.output?.reason || 'Output rule triggered','BLOCKED');
          setStep('delivery','passed','Safe fallback delivered','✓');
          $('#pipeline-state').textContent = 'STOPPED AT OUTPUT';
          showResult('Generated response blocked','The output check rejected the model response and substituted a fallback.','danger');
        }
      }
    }
    addMessage('assistant', data.response || 'No response was returned.', data.blocked ? 'Sentinel · Safe fallback' : 'Sentinel assistant');
  } catch (err) {
    ['input','model','output'].forEach(n => { if (!$(`#step-${n}`).classList.contains('passed')) setStep(n,'failed','Request could not complete','ERROR'); });
    setStep('delivery','skipped','No response delivered','SKIPPED');
    $('#pipeline-state').textContent = 'REQUEST ERROR'; showResult('Could not complete request',err.message || 'Check the Flask server and try again.','danger');
    addMessage('assistant',`I couldn't complete that request. ${err.message || 'Please check the local backend.'}`,'System message');
  } finally { busy = false; send.disabled = false; send.innerHTML = 'Run guardrails <span>↗</span>'; input.focus(); }
}
form.addEventListener('submit', e => { e.preventDefault(); const value = input.value.trim(); if (!value) return; input.value = ''; runPipeline(value); });
document.querySelectorAll('.suggestion').forEach(btn => btn.addEventListener('click', () => { input.value = btn.textContent; input.focus(); }));
$('.menu-toggle').addEventListener('click', () => document.querySelector('nav').classList.toggle('open'));
document.querySelectorAll('nav a').forEach(a => a.addEventListener('click', () => document.querySelector('nav').classList.remove('open')));
const observer = new IntersectionObserver(entries => entries.forEach(entry => { if (entry.isIntersecting) { entry.target.classList.add('visible'); observer.unobserve(entry.target); } }), {threshold:.12});
document.querySelectorAll('.reveal, .reason-card, .flow-step, .architecture-card, .stack-grid, .closing-grid').forEach(el => { el.classList.add('will-reveal'); observer.observe(el); });
